#!/usr/bin/env node
// Write a cross-language test vector into the chaincode's testdata.
//
// The chaincode verifies signatures this service produces, so the two
// implementations of the quote encoding have to agree byte for byte. They are
// in different languages and nothing but care keeps them in step, which is not
// good enough for something whose failure mode is "every quote is rejected and
// the error says the signature is wrong".
//
// So: this writes a quote, its canonical bytes and a real signature. A Go test
// re-derives the bytes with its own implementation, compares them, and
// verifies the signature with its own verifier. Either side drifting fails
// that test.
//
// The key here is generated fresh and written into the fixture, so the vector
// is self-contained and no signing key is committed.

import crypto from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { quoteBytes, signQuote, verifyQuote } from './quote.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', '..', '..', 'chaincode', 'settlement', 'settlement',
  'testdata', 'quote-vector.json');

const { privateKey, publicKey } = crypto.generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
const privateKeyPem = privateKey.export({ type: 'pkcs8', format: 'pem' });
const publicKeyPem = publicKey.export({ type: 'spki', format: 'pem' });

// Deliberately awkward values: a quote ID that could run into the oracle ID if
// the fields were not length-prefixed, a rate that is not a round number, and
// a non-zero slippage.
const quote = {
  quoteID: 'q-cross-lang-1',
  oracleID: 'tributary-fx-1',
  baseCcy: 'AED',
  quoteCcy: 'INR',
  rateNum: 227431,
  rateDen: 10000,
  expiresAt: 1794000000,
  maxSlippageBps: 25,
};

const canonical = quoteBytes(quote);
const signature = signQuote(quote, privateKeyPem);
if (!verifyQuote(quote, signature, publicKeyPem)) {
  console.error('refusing to write a vector whose signature does not verify locally');
  process.exit(1);
}

const vector = {
  note: 'Generated by services/oracle (npm run vector). Checked by TestQuote_MatchesTheOracleServiceEncoding.',
  quote,
  canonicalBase64: canonical.toString('base64'),
  canonicalText: canonical.toString('utf8'),
  publicKeyPEM: publicKeyPem,
  signatureBase64: signature,
};

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, `${JSON.stringify(vector, null, 2)}\n`);
process.stderr.write(`wrote ${OUT}\n`);
process.stderr.write(`canonical bytes: ${canonical.length}\n`);
